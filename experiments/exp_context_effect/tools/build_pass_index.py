"""Build per-group PASS-index files so curators can see every past successful PNG.

Scans judgments/batch_*/labels.json across all batches, groups PASS + A verdicts
by group, and writes `groups/<group_dir>/pass_index.md` — a markdown table of
item_id | verdict | batch | attempt PNG path.

Purpose (v11 clarification of v10): curators reflecting during errata scans
should not stop at the code bank / drawer_memory abstractions. They should be
able to open the actual PNGs of past-successful attempts, learn from what
worked visually, and use that to shape retry queues + memory updates. Bank
files encode a synthesis; the raw PASS PNGs are the ground truth of "what
this group knows how to draw well."

Usage:
    python3 tools/build_pass_index.py
    # writes to groups/G{1..4}_*/pass_index.md
"""
import json
import os
import glob
import re
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.dirname(HERE)
# G1 is the control (no memory). Never build a PASS-index for it, even
# though its attempts exist and its labels have PASS verdicts — the index
# is itself a memory artifact.
GDIRS = {"G2":"G2_free_form","G3":"G3_coords","G4":"G4_grid","G5":"G5_code_bank_mmh"}


def load_all_labels():
    """Yield (batch_name, attempt_key, meta) across every judged batch."""
    for lp in sorted(glob.glob(os.path.join(EXP, "judgments", "batch_*", "labels.json"))):
        batch = os.path.basename(os.path.dirname(lp))
        try:
            labs = json.load(open(lp, encoding="utf-8"))
        except Exception:
            continue
        for aid, meta in labs.items():
            yield batch, aid, meta


def resolve_attempt_dir(item_id, is_retry, group):
    """From attempt_key/item_id, guess the on-disk attempt dir name."""
    # item_id in labels comes from manifest — for retries it looks like
    # p2_radical_011_匕__retry_4__G3 (or __rerun suffix).
    if not is_retry:
        return item_id
    # strip group suffix
    m = re.match(r'^(.+?)__retry_(\d+)(?:__G[1-5])?(?:__rerun)?$', item_id)
    if not m:
        return item_id
    base, n = m.group(1), int(m.group(2))
    rerun = "__rerun" if item_id.endswith("__rerun") else ""
    return f"{base}__retry_{n}{rerun}"


def build_group_index(group):
    """Return list of {item_id, char, verdict, batch, png_path, dir}."""
    gdir = GDIRS[group]
    rows = []
    for batch, aid, meta in load_all_labels():
        if meta.get("actual_group") != group:
            continue
        if meta.get("verdict") not in ("PASS", "A"):
            continue
        iid = meta.get("item_id", "")
        is_retry = "__retry_" in iid
        attempt_dir = resolve_attempt_dir(iid, is_retry, group)
        # extract char from item_id (last _ segment, or from target_label)
        char = meta.get("target_label", "")
        # target_label may include annotations like "(retry #N)"; strip
        char = re.sub(r'\s*\(.*\)$', '', char).strip()
        if not char:
            # try tail of item_id after the last underscore before optional suffix
            base = re.sub(r'__retry_\d+.*$', '', iid)
            char = base.split('_')[-1]
        png_path = os.path.join(EXP, "groups", gdir, "attempts", attempt_dir, f"01_{char}.png")
        rel = os.path.relpath(png_path, EXP)
        exists = os.path.isfile(png_path)
        rows.append({
            "item_id": iid,
            "char": char,
            "verdict": meta["verdict"],
            "batch": batch.replace("batch_", ""),
            "png_rel": rel,
            "png_exists": exists,
            "phase": meta.get("phase", ""),
        })
    return rows


def write_index_md(group, rows):
    gdir = GDIRS[group]
    out_path = os.path.join(EXP, "groups", gdir, "pass_index.md")
    a_count = sum(1 for r in rows if r["verdict"] == "A")
    p_count = sum(1 for r in rows if r["verdict"] == "PASS")
    missing = sum(1 for r in rows if not r["png_exists"])

    lines = [
        f"# {group} — PASS-index",
        "",
        "*Auto-generated by `tools/build_pass_index.py`. Do not edit by hand.*",
        "",
        f"Every attempt this group has produced that a human judged PASS or A, ",
        f"with a path to its rendered PNG. **Curators**: consult this file during ",
        f"errata scans and reflection. When deciding a retry queue or updating memory, ",
        f"open the actual PNGs of past successes to see what visually worked — ",
        f"don't rely only on the abstract memory (bank files, principles, drawer_memory). ",
        f"A picture of a past PASS carries information the bank encoding drops.",
        "",
        f"**Totals**: {p_count} PASS + {a_count} A = {p_count + a_count} successful renders",
        f" ({missing} PNGs missing on disk — likely from cleaned-up retry_v2 dirs).",
        "",
        "| # | verdict | item_id | char | batch | PNG path |",
        "|---|---------|---------|------|-------|----------|",
    ]
    for i, r in enumerate(rows, 1):
        exists_mark = "" if r["png_exists"] else " *(missing)*"
        lines.append(
            f"| {i} | **{r['verdict']}** | `{r['item_id']}` | {r['char']} | {r['batch']} | `{r['png_rel']}`{exists_mark} |"
        )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return out_path, p_count, a_count


def main():
    print(f"Building PASS-index for memory groups {sorted(GDIRS)} (G1 excluded — control has no memory)...")
    for g in sorted(GDIRS):
        rows = build_group_index(g)
        out, p, a = write_index_md(g, rows)
        print(f"  {g}: {p} PASS + {a} A = {p+a} rows → {out}")


if __name__ == "__main__":
    main()
