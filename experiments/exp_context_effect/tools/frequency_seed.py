_ALL_TIERS = _TIER1 + _TIER2 + _TIER3

# Build the deduplicated set and preserve first-occurrence rank
SEED_RANK = {}
for _i, _c in enumerate(_ALL_TIERS):
    if _c not in SEED_RANK:
        SEED_RANK[_c] = len(SEED_RANK) + 1

SEED_SET = set(SEED_RANK)


def is_common(ch: str) -> bool:
    """Return True iff the character is in the common-frequency seed."""
    return ch in SEED_SET


def rank(ch: str) -> int:
    """Return 1-based frequency rank, or a large sentinel if not in seed."""
    return SEED_RANK.get(ch, 1_000_000)


